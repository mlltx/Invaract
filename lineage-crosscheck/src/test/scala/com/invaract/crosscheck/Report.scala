package com.invaract.crosscheck

/** One corpus job's run: how Invaract's lineage differs from each reference, and Invaract's lineage itself. */
final case class Outcome(job: Job, diffs: Map[Reference, List[String]], invaract: List[String])

/** What a corpus run is written down as: the baseline (Invaract's lineage of every job and every difference, exactly,
  * for the spec to hold the next run to) and the docs-site page (the same, for a reader: each job's code, what Invaract
  * publishes for it, and each difference with its reason). */
object Report {

  /** What Invaract's Spark lineage does not do that no corpus job measures (a job cannot show what needs a metastore, a
    * catalog service or a long-running stream), kept beside the measured gaps so the page lists every limit. */
  private val Limits =
    """
      |Limits of Invaract's Spark lineage that no job on this page measures:
      |
      |- **A table its own write creates, in a catalog that chooses where to store it.** Invaract names a table a write
      |  creates by where it will be stored when Spark's configuration says (a `LOCATION`, the session catalog, an Iceberg
      |  Hadoop or JDBC catalog). In a catalog that chooses the location when it creates the table (an Iceberg Hive, REST
      |  or Glue catalog, for example), Invaract names the table by its catalog identifier.
      |- **Streaming queries.** Invaract checks a streaming query written to a sink once, when it starts, and publishes
      |  that lineage, not one per micro-batch. A `foreachBatch` function's writes are checked and published batch by
      |  batch (the `foreach-batch` job).
      |- **User-defined functions.** A column a UDF computes has the UDF's input columns as its sources, typed
      |  `TRANSFORMATION` and described as opaque: what the function does with them is not known.
      |- **RDDs.** A DataFrame made from an RDD has the files the RDD read as its inputs, with no column lineage through
      |  the RDD.
      |- **Operators Invaract does not translate.** An operator Invaract does not translate is a boundary: a column
      |  computed through it has no sources.
      |- **A MERGE's DELETE clauses, and the rows it leaves.** The rows a DELETE clause removes are not written, so its
      |  condition is not reported. Rows no clause touches are not counted, as openlineage-spark counts them.
      |""".stripMargin

  def baseline(results: List[Outcome]): String = {
    val sb = new StringBuilder
    sb ++= "# lineage-crosscheck baseline: Invaract's Spark column lineage of each job, and how it differs from each reference.\n"
    sb ++= "# Generated by LineageCrossCheckSpec (CROSSCHECK_UPDATE=true sbt test); each difference is explained in Corpus.scala.\n"
    for (o <- results) {
      sb ++= s"\n[${o.job.id} invaract]\n"
      o.invaract.foreach(l => sb ++= s"  $l\n")
      for (reference <- Reference.all) {
        sb ++= s"[${o.job.id} vs ${reference.name}]\n"
        if (o.diffs(reference).isEmpty) sb ++= "agree\n" else o.diffs(reference).foreach(l => sb ++= s"  $l\n")
      }
    }
    sb.toString
  }

  private def cell(o: Outcome, reference: Reference): String =
    if (o.diffs(reference).isEmpty) "✓ agrees"
    else s"[differs](#${o.job.id}): ${o.job.notes.get(reference).map(_.cause.label).getOrElse("unexplained")}"

  /** The differences where Invaract reports what a reference misses: its limit, not Invaract's, and lineage it lacks. */
  private def missedBy(o: Outcome, reference: Reference): List[String] =
    if (o.job.notes.get(reference).exists(_.cause == Cause.Reference)) o.diffs(reference).filter(_.contains("only invaract")) else Nil

  private def title(reference: Reference): String = reference match {
    case Reference.OpenLineageSpark => "openlineage-spark"
    case Reference.Spline           => "Spline"
  }

  private def code(job: Job): String = "```scala\n" + CorpusSource.code(job.id) + "\n```\n"
  private def lineage(o: Outcome): String = "```text\n" + o.invaract.mkString("\n") + "\n```\n"

  def page(results: List[Outcome], versions: String): String = {
    val sb = new StringBuilder
    val n = results.size
    def agreeing(r: Reference) = results.count(_.diffs(r).isEmpty)
    sb ++= """---
      |title: Spark Column Lineage Coverage
      |description: How the column lineage Invaract publishes for Spark jobs compares with openlineage-spark and Spline, construct by construct, measured on real jobs.
      |---
      |
      |""".stripMargin
    sb ++= "<!-- Generated by lineage-crosscheck (LineageCrossCheckSpec; run with CROSSCHECK_UPDATE=true to regenerate). Do not edit by hand. -->\n\n"
    sb ++= s"""Invaract publishes column lineage for Spark jobs in its [OpenLineage events](/guides/openlineage/), traced from the
      |job's analyzed plan. This page shows how complete and correct that lineage is. Each of the $n Spark jobs below runs once,
      |with three tools capturing lineage from the same run: Invaract, [openlineage-spark](https://openlineage.io/docs/integrations/spark/)
      |(OpenLineage's own Spark integration) and the [Spline](https://absaoss.github.io/spline/) agent. Versions measured:
      |$versions. For each job's write, the comparison covers:
      |
      |- **datasets**: the input and output datasets, named by the [OpenLineage naming conventions](https://openlineage.io/docs/spec/naming);
      |- **direct lineage**: which input columns each output column's value comes from, and how (`IDENTITY`,
      |  `TRANSFORMATION`, `AGGREGATION`, masking);
      |- **indirect lineage**: which input columns decide the output's rows or their order (`FILTER`, `JOIN`, `GROUP_BY`,
      |  `SORT`), or which value an output column takes (`CONDITIONAL`, `WINDOW`).
      |
      |Spline does not classify edges, so against Spline every column an output column depends on is compared, by value or not.
      |
      |Invaract agrees with openlineage-spark on ${agreeing(Reference.OpenLineageSpark)} of $n jobs, and with Spline on
      |${agreeing(Reference.Spline)} of $n. A job agrees only when every dataset and every edge, with its type, is the same;
      |each difference is listed below with its reason. Most come from one of two things: openlineage-spark reads Spark's
      |*optimized* plan, so it also reports columns the optimizer added (such as an `isnotnull` filter on a join key); or
      |another tool misses part of the plan Invaract follows ([what Invaract captures that the others
      |miss](#what-invaract-captures-that-the-others-miss)). The rest are conventions, and [Invaract's known gaps](#known-gaps).
      |
      |## Check it yourself
      |
      |Everything on this page comes from one run of the `lineage-crosscheck` module, and the code shown for each job is the
      |code that ran. To run it, from a checkout of Invaract with Java 11 or later and sbt:
      |
      |```bash
      |./dev/build                        # builds Invaract and publishes it locally
      |cd lineage-crosscheck && sbt test  # runs every job under all three tools and compares them
      |```
      |
      |The run fails when any job's lineage, Invaract's or a reference's, differs from what is recorded here
      |(`lineage-crosscheck/src/test/resources/crosscheck-baseline.txt`). CI runs it on every pull request and every push,
      |so lineage verified here cannot change without the change being reviewed. After an intended change, explain it in
      |`Corpus.scala` and run `CROSSCHECK_UPDATE=true sbt test` to rewrite the baseline and this page.
      |
      |In the code, `s` is the job's `SparkSession` and `f` the shared inputs: `f.orders(s)` and `f.customers(s)` read
      |Parquet, `f.events(s)` JSON. A job that is a DataFrame expression is written as Parquet to `out`.
      |
      || Input | Format | Columns |
      ||---|---|---|
      || `orders` | Parquet | `id`, `customer_id`, `amount`, `status` |
      || `customers` | Parquet | `customer_id`, `name`, `country`, `email` |
      || `events` | JSON | `id`, `payload` (a struct of `a` and `b`), `tags` (an array) |
      || `sales.csv` | CSV | `region`, `amount` |
      || `ACCOUNTS` | H2, over JDBC | `ID`, `BALANCE` |
      |
      |In the lineage, `<in>` is the inputs' directory and `<out>` the job's own. `field <- dataset.column` is direct
      |lineage, `field <~ dataset.column` indirect (`*`: on every row of the output), each with its OpenLineage type.
      |
      |""".stripMargin
    sb ++= "## Summary\n\n"
    sb ++= "| Spark construct | Job | openlineage-spark | Spline |\n|---|---|---|---|\n"
    for (o <- results)
      sb ++= s"| ${o.job.construct} | ${o.job.description} (`${o.job.id}`) | ${cell(o, Reference.OpenLineageSpark)} | ${cell(o, Reference.Spline)} |\n"

    sb ++= "\n## What Invaract captures that the others miss\n\n"
    sb ++= """Jobs where Invaract reports lineage another tool does not, because that tool does not follow that part of the plan.
      |Each shows the job's code, what Invaract publishes for it, and the lineage each other tool leaves out.
      |""".stripMargin
    for (o <- results) {
      val missed = Reference.all.map(r => r -> missedBy(o, r)).filter(_._2.nonEmpty)
      if (missed.nonEmpty) {
        sb ++= s"\n### ${o.job.description.capitalize} (`${o.job.id}`)\n\n" + code(o.job) + "\nInvaract publishes:\n\n" + lineage(o)
        for ((reference, lines) <- missed) {
          sb ++= s"\n${title(reference)} leaves out: ${o.job.notes(reference).text}\n\n"
          sb ++= "```text\n" + lines.map(_.replace("only invaract: ", "")).mkString("\n") + "\n```\n"
        }
      }
    }

    val gaps = results.flatMap(o => o.job.notes.toList.collect { case (r, note) if note.cause == Cause.Gap => (o.job, r, note) })
    sb ++= "\n## Known gaps\n\n"
    if (gaps.isEmpty) sb ++= "None of the jobs on this page shows a gap in Invaract's lineage.\n"
    else gaps.map(_._1).distinct.foreach { job =>
      // one entry per job: its note against openlineage-spark when it has one (Reference.all's order), which says most
      val text = gaps.collectFirst { case (j, _, note) if j == job => note.text }.get
      sb ++= s"- **${job.description.capitalize}** (`${job.id}`): $text\n"
    }
    sb ++= Limits

    sb ++= "\n## Every job\n"
    for (o <- results) {
      sb ++= s"\n### ${o.job.id}\n\n${o.job.construct}: ${o.job.description}.\n\n" + code(o.job) + "\nInvaract publishes:\n\n" + lineage(o)
      for (reference <- Reference.all) {
        val note = o.job.notes.get(reference)
        if (o.diffs(reference).isEmpty) sb ++= s"\n**Against ${title(reference)}**: agrees.\n"
        else {
          sb ++= s"\n**Against ${title(reference)}** (${note.map(_.cause.label).getOrElse("unexplained")}): ${note.map(_.text).getOrElse("")}\n\n"
          sb ++= "```text\n" + o.diffs(reference).mkString("\n") + "\n```\n"
        }
      }
    }
    sb.toString
  }
}
