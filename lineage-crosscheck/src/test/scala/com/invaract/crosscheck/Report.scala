package com.invaract.crosscheck

/** What a corpus run is written down as: the baseline (every difference, exactly, for the spec to hold the next run
  * to) and the docs-site page (the same, for a reader, with each difference's reason and Invaract's gaps listed). */
object Report {

  type Results = List[(Job, Map[Reference, List[String]])]

  def baseline(results: Results): String = {
    val sb = new StringBuilder
    sb ++= "# lineage-crosscheck baseline: how Invaract's Spark column lineage differs from each reference, job by job.\n"
    sb ++= "# Generated by LineageCrossCheckSpec (CROSSCHECK_UPDATE=true sbt test); each difference is explained in Corpus.scala.\n"
    for ((job, diffs) <- results; reference <- Reference.all) {
      val lines = diffs(reference)
      sb ++= s"\n[${job.id} vs ${reference.name}]\n"
      if (lines.isEmpty) sb ++= "agree\n" else lines.foreach(l => sb ++= s"  $l\n")
    }
    sb.toString
  }

  private def cell(job: Job, diffs: Map[Reference, List[String]], reference: Reference): String =
    if (diffs(reference).isEmpty) "✓ agrees"
    else s"[differs](#${job.id}): ${job.notes.get(reference).map(_.cause.label).getOrElse("unexplained")}"

  def page(results: Results, versions: String): String = {
    val sb = new StringBuilder
    val n = results.size
    def agreeing(r: Reference) = results.count(_._2(r).isEmpty)
    sb ++= """---
      |title: Spark Column Lineage Coverage
      |description: How the column lineage Invaract publishes for Spark jobs compares with openlineage-spark and Spline, construct by construct, measured on real jobs.
      |---
      |
      |""".stripMargin
    sb ++= "<!-- Generated by lineage-crosscheck (LineageCrossCheckSpec; run with CROSSCHECK_UPDATE=true to regenerate). Do not edit by hand. -->\n\n"
    sb ++= s"""Invaract publishes column lineage for Spark jobs in its [OpenLineage events](/guides/openlineage/), traced from the
      |job's analyzed plan. This page shows how complete and correct that lineage is. Each of the $n Spark jobs below runs once,
      |with three tools capturing lineage from the same run: Invaract, [openlineage-spark](https://openlineage.io/docs/integrations/spark/)
      |(OpenLineage's own Spark integration) and the [Spline](https://absaoss.github.io/spline/) agent ($versions). For each
      |job's write, the comparison covers:
      |
      |- **datasets**: the input and output datasets, named by the [OpenLineage naming conventions](https://openlineage.io/docs/spec/naming);
      |- **direct lineage**: which input columns each output column's value comes from, and how (`IDENTITY`,
      |  `TRANSFORMATION`, `AGGREGATION`, masking);
      |- **indirect lineage**: which input columns decide the output's rows or their order (`FILTER`, `JOIN`, `GROUP_BY`,
      |  `SORT`), or which value an output column takes (`CONDITIONAL`, `WINDOW`).
      |
      |Spline does not classify edges, so against Spline every column an output column depends on is compared, by value or not.
      |
      |Invaract agrees with openlineage-spark on ${agreeing(Reference.OpenLineageSpark)} of $n jobs, and with Spline on
      |${agreeing(Reference.Spline)} of $n. Each difference is listed below with its reason. Most come from one of two
      |things: openlineage-spark reads Spark's *optimized* plan, so it also reports columns the optimizer added (such as a
      |`isnotnull` filter on a join key); or another tool misses part of the plan Invaract follows. The rest are
      |[Invaract's known gaps](#known-gaps).
      |
      |""".stripMargin
    sb ++= "| Spark construct | Job | openlineage-spark | Spline |\n|---|---|---|---|\n"
    for ((job, diffs) <- results)
      sb ++= s"| ${job.construct} | ${job.description} (`${job.id}`) | ${cell(job, diffs, Reference.OpenLineageSpark)} | ${cell(job, diffs, Reference.Spline)} |\n"
    val gaps = results.flatMap { case (job, _) => job.notes.toList.collect { case (r, note) if note.cause == Cause.Gap => (job, r, note) } }
    sb ++= "\n## Known gaps\n\n"
    if (gaps.isEmpty) sb ++= "None of the jobs above shows a gap in Invaract's lineage.\n"
    else gaps.map(_._1).distinct.foreach { job =>
      // one entry per job: its note against openlineage-spark when it has one (Reference.all's order), which says most
      val text = gaps.collectFirst { case (j, _, note) if j == job => note.text }.get
      sb ++= s"- **${job.description.capitalize}** (`${job.id}`): $text\n"
    }
    sb ++= "\n## Differences, job by job\n"
    for ((job, diffs) <- results if Reference.all.exists(r => diffs(r).nonEmpty)) {
      sb ++= s"\n### ${job.id}\n\n${job.description.capitalize}.\n"
      for (reference <- Reference.all if diffs(reference).nonEmpty) {
        val note = job.notes.get(reference)
        sb ++= s"\n**Against ${reference.name}** (${note.map(_.cause.label).getOrElse("unexplained")}): ${note.map(_.text).getOrElse("")}\n\n"
        sb ++= "```text\n" + diffs(reference).mkString("\n") + "\n```\n"
      }
    }
    sb.toString
  }
}
